import type { RatchetPlugin } from '../plugin/types.js';

const HEADER = `// GENERATED by \`ratchet generate\` — do not edit.
// Every enabled plugin's console module (\`RatchetPlugin.console\`), in plugin order — resolved by
// the console build as the \`ratchet:plugins\` virtual module and read by \`ConsoleApp\`.

`;

/** `.ratchet/console-plugins.ts` — one default import per plugin that ships console UI. */
export function generateConsolePluginsSource(plugins: readonly RatchetPlugin[]): string {
  const specifiers = plugins.flatMap((p) => (p.console === undefined ? [] : Array.isArray(p.console) ? p.console : [p.console]));
  const imports = specifiers.map((specifier, i) => `import plugin${i} from '${specifier}';`);
  const list = specifiers.map((_, i) => `plugin${i}`).join(', ');
  return (
    HEADER +
    [`import type { ConsolePlugin } from '@egig/ratchet/console/client';`, ...imports, ``, `export const consolePlugins: ConsolePlugin[] = [${list}];`, ``].join('\n')
  );
}
